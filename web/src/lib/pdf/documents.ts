/*
 * Read once per process, not per request - the two files are ~240 KB and every
 * download would otherwise re-parse them. Lazy, so nothing touches the disk
 * while Next is collecting routes at build time.
 *
 * No mono face. Record ids are set in the semibold instead: a third embedded
 * font to letter-space `INV-1` is not worth 120 KB on every download.
 */
let faces: { regular: Font; semibold: Font } | null = null;

function fonts() {
  if (!faces) {
    const dir = join(process.cwd(), "src/lib/pdf/fonts");
    faces = {
      regular: loadFont(join(dir, "Montserrat-Regular.ttf"), "Montserrat"),
      semibold: loadFont(join(dir, "Montserrat-SemiBold.ttf"), "Montserrat-SemiBold"),
    };
  }
  return faces;
}

