// Layout
// ---------------------------------------------------------------------------

const M = 48; // page margin
const PAD = 16; // padding inside a block
const BAND = 150; // the indigo hero block

/** A container: square, hairline border, white. The `Card` of this document. */
function block(p: Page, x: number, y: number, w: number, h: number, fill = c.surface) {
  p.rect(x, y, w, h, rgb(c.line));
  p.rect(x + 0.75, y + 0.75, w - 1.5, h - 1.5, rgb(fill));
}

/** Baseline that puts a cap-height line on the centre of a band. */
function centred(cy: number, size: number, font: Font) {
  return cy + ((font.capHeight / 1000) * size) / 2;
}

/** The ◆ + word tag, as a round control on a square page. Returns its width. */
function simulatedTag(
  p: Page,
  x: number,
  y: number,
  label: string,
  fill: string,
  ink: string,
) {
  const { semibold } = fonts();
  const size = 9.5;
  const h = 19;
  const w = p.measure(label, { font: semibold, size }) + 32;
  p.pill(x, y, w, h, rgb(fill));
  p.diamond(x + 13, y + h / 2, 3.1, rgb(ink));
  p.text(label, x + 21, centred(y + h / 2, size, semibold), {
    font: semibold,
    size,
    color: rgb(ink),
  });
  return w;
}

type Cell = { label: string; value: string; hint?: string };

/** The figures strip off the evidence screen: square cells, hairline gaps. */
function figures(p: Page, x: number, y: number, w: number, cells: Cell[]) {
  const { regular, semibold } = fonts();
  const h = 78;
  p.rect(x, y, w, h, rgb(c.line));
  const cw = (w - 1.5 - (cells.length - 1)) / cells.length;

  cells.forEach((cell, i) => {
    const cx = x + 0.75 + i * (cw + 1);
    p.rect(cx, y + 0.75, cw, h - 1.5, rgb(c.surface));
    p.text(cell.label, cx + 14, p.lineTop(y + 14, 9, semibold), {
      font: semibold,
      size: 9,
      color: rgb(c.faint),
    });
    p.text(cell.value, cx + 14, p.lineTop(y + 28, 23, semibold), {
      font: semibold,
      size: 23,
      color: rgb(c.foreground),
    });
    if (cell.hint) {
      p.text(cell.hint, cx + 14, p.lineTop(y + 60, 8.5, regular), {
        font: regular,
        size: 8.5,
        color: rgb(c.faint),
      });
    }
  });
  return y + h;
}

/** A lowercase section label, matching `SectionTitle`. */
function sectionTitle(p: Page, x: number, y: number, text: string) {
  const { semibold } = fonts();
  p.text(text, x, p.lineTop(y, 9.5, semibold), {
    font: semibold,
    size: 9.5,
    color: rgb(c.faint),
  });
  return y + 22;
}

