/**
 * The two documents a simulated supplier event delivers: the invoice and the
 * credit note.
 *
 * They are laid out in the prototype's own visual language, because that is the
 * whole point of offering them - a reviewer who clicks "download" should get
 * something that plainly belongs to the same product as the screen they clicked
 * it from. Containers square, controls round, lowercase chrome, the indigo
 * block on the grey field, and the ◆ coral tag that means simulated.
 *
 * Two deliberate absences:
 *
 * - **No prices.** `initial.json` carries quantities only, and the working
 *   agreement forbids inventing a price. The document says so in as many words
 *   rather than leaving a blank column a reader might fill in themselves.
 * - **No client identity.** No logo, no mark, no wordmark, and no named
 *   bill-to. The assignment is an exercise and does not imply the client
 *   commissioned or endorsed any of this, so the styling is borrowed and the
 *   identity is not.
 */

