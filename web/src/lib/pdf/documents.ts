export type DocumentKind = "invoice" | "credit-note";

export function renderDocument(
  kind: DocumentKind,
  facts: EventFacts,
  locale: "en" | "de",
): { body: Buffer; filename: string; title: string } {
  const s = STRINGS[locale];
  const { regular, semibold } = fonts();
  const p = new Page();
  const W = p.width;
  const CW = W - M * 2;

  const isInvoice = kind === "invoice";
  const id = isInvoice ? facts.invoiceId : facts.creditId;
  const notes = facts.noteIds.join(" + ");

  // The grey field everything floats on.
  p.rect(0, 0, W, p.height, rgb(c.background));

  // --- the indigo block -----------------------------------------------------
  p.rect(0, 0, W, BAND, rgb(c.brand));
  p.rect(M, 44, 10, 10, rgb(c.brandInk));
  p.text(
    isInvoice ? s.invoiceKicker : s.creditKicker,
    M + 18,
    p.lineTop(44, 10.5, semibold),
    { font: semibold, size: 10.5, color: rgb(c.brandSoft) },
  );
  p.text(id, M, p.lineTop(72, 34, semibold), {
    font: semibold,
    size: 34,
    color: rgb(c.brandInk),
  });
  p.text(
    isInvoice
      ? `${facts.part} · ${facts.orderId}`
      : `${facts.invoiceId} · ${facts.orderId}`,
    M,
    p.lineTop(118, 11, regular),
    { font: regular, size: 11, color: rgb(c.brandSoft) },
  );

  const tagWidth = p.measure(s.simulated, { font: semibold, size: 9.5 }) + 32;
  simulatedTag(p, W - M - tagWidth, 44, s.simulated, c.simSoft, c.sim);

  // --- the figures ----------------------------------------------------------
  let y = BAND + 30;
  y = figures(
    p,
    M,
    y,
    CW,
    isInvoice
      ? [
          { label: s.figInvoiced, value: String(facts.invoiceQty), hint: facts.part },
          { label: s.figNotes, value: String(facts.noteIds.length), hint: notes },
          { label: s.figOrder, value: facts.orderId },
        ]
      : [
          { label: s.figCredited, value: String(facts.creditQty), hint: facts.part },
          { label: s.figAgainst, value: facts.invoiceId, hint: notes },
          { label: s.figOrder, value: facts.orderId },
        ],
  );

  // --- what the document says ----------------------------------------------
  y = sectionTitle(p, M, y + 30, s.says);

  const description = isInvoice
    ? s.invoiceLine(facts.part, notes)
    : s.creditLine(facts.invoiceId, facts.creditQty);
  const qtyColumn = 78;
  const descWidth = CW - PAD * 2 - 74 - qtyColumn;
  const descLines = p.wrap(description, descWidth, { font: regular, size: 10 });
  const rowHeight = Math.max(34, descLines.length * 14 + 20);
  const tableHeight = 26 + rowHeight;

  block(p, M, y, CW, tableHeight);
  const th = { font: regular, size: 8.5, color: rgb(c.faint) } as const;
  p.text(s.thRecord, M + PAD, p.lineTop(y + 8, 8.5, regular), th);
  p.text(s.thDescription, M + PAD + 74, p.lineTop(y + 8, 8.5, regular), th);
  p.text(s.thQuantity, M + CW - PAD, p.lineTop(y + 8, 8.5, regular), {
    ...th,
    align: "end",
  });
  p.line(M + 0.75, y + 26, M + CW - 0.75, y + 26, rgb(c.line));

  p.text(id, M + PAD, p.lineTop(y + 36, 10, semibold), {
    font: semibold,
    size: 10,
    color: rgb(c.foreground),
  });
  descLines.forEach((line, i) => {
    p.text(line, M + PAD + 74, p.lineTop(y + 36 + i * 14, 10, regular), {
      font: regular,
      size: 10,
      color: rgb(c.muted),
    });
  });
  p.text(
    String(isInvoice ? facts.invoiceQty : facts.creditQty),
    M + CW - PAD,
    p.lineTop(y + 36, 10, semibold),
    { font: semibold, size: 10, color: rgb(c.foreground), align: "end" },
  );
  y += tableHeight;

  // --- what it does not say -------------------------------------------------
  y = sectionTitle(p, M, y + 30, s.limitsHeading);
  const limits = isInvoice ? s.invoiceLimits : s.creditLimits(facts.invoiceId);
  const limitLines = p.wrap(limits, CW - PAD * 2, { font: regular, size: 10 });
  const limitsHeight = limitLines.length * 15 + PAD * 2 - 2;
  block(p, M, y, CW, limitsHeight);
  limitLines.forEach((line, i) => {
    p.text(line, M + PAD, p.lineTop(y + PAD - 3 + i * 15, 10, regular), {
      font: regular,
      size: 10,
      color: rgb(c.muted),
    });
  });
  y += limitsHeight;

  // --- the label the exercise requires --------------------------------------
  // Anchored to the foot of the page rather than to the block above it. A
  // document runs short or long depending on how much the supplier billed; the
  // label that says none of this is real should sit in the same place either
  // way, and it leaves the whitespace where a document normally has it.
  const simLines = p.wrap(s.simBody, CW - PAD * 2, { font: regular, size: 9.5 });
  const simHeight = 30 + simLines.length * 14 + PAD;
  y = Math.max(y + 30, p.height - 64 - 30 - simHeight);
  p.rect(M, y, CW, simHeight, rgb(c.sim));
  p.rect(M + 0.75, y + 0.75, CW - 1.5, simHeight - 1.5, rgb(c.simSoft));
  p.diamond(M + PAD + 4, y + PAD + 1, 3.6, rgb(c.sim));
  p.text(s.simHeading, M + PAD + 13, centred(y + PAD + 1, 10, semibold), {
    font: semibold,
    size: 10,
    color: rgb(c.sim),
  });
  simLines.forEach((line, i) => {
    p.text(line, M + PAD, p.lineTop(y + 28 + i * 14, 9.5, regular), {
      font: regular,
      size: 9.5,
      color: rgb(c.foreground),
    });
  });

  // --- footer ---------------------------------------------------------------
  const foot = p.height - 64;
  p.line(M, foot, W - M, foot, rgb(c.line));
  p.text(s.footer, M, p.lineTop(foot + 12, 9, semibold), {
    font: semibold,
    size: 9,
    color: rgb(c.faint),
  });
  const stamp = new Date().toISOString().replace("T", " ").slice(0, 16);
  p.text(s.generated(`${stamp} UTC`), W - M, p.lineTop(foot + 12, 9, regular), {
    font: regular,
    size: 9,
    color: rgb(c.faint),
    align: "end",
  });

  const title = `${id} — ${isInvoice ? s.invoiceKicker : s.creditKicker}`;
  return { body: p.render(title), filename: `${id}.pdf`, title };
}
